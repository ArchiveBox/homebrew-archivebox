#!/usr/bin/env python3
"""Build Formula/archivebox.rb from an exact published ArchiveBox version."""

from __future__ import annotations

import json
import os
import textwrap
import urllib.request
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
FORMULA_PATH = REPO_ROOT / "Formula" / "archivebox.rb"


def github_output(**values: str) -> None:
    output_path = os.environ.get("GITHUB_OUTPUT")
    if not output_path:
        return
    with open(output_path, "a", encoding="utf-8") as output:
        for key, value in values.items():
            output.write(f"{key}={value}\n")


def formula_template(version: str, wheel_url: str, wheel_sha256: str) -> str:
    return textwrap.dedent(
        f"""\
        # Auto-generated by bin/build_brew.sh.
        # Runs an exact published ArchiveBox wheel through uv's normal tool path.

        class Archivebox < Formula
          desc "Self-hosted internet archiving solution"
          homepage "https://archivebox.io"
          url "{wheel_url}"
          version "{version}"
          sha256 "{wheel_sha256}"
          license "MIT"

          depends_on "uv"

          def install
            (bin/"archivebox").write <<~SH
              #!/bin/sh
              exec uv tool run --from "{wheel_url}" archivebox "$@"
            SH
            chmod 0755, bin/"archivebox"
          end

          def caveats
            <<~EOS
              ArchiveBox {version} runs from its verified PyPI wheel through uv.

              To create a collection and install runtime extractors:
                mkdir -p ~/archivebox/data
                cd ~/archivebox/data
                archivebox init
                archivebox install
            EOS
          end

          test do
            (testpath/"data").mkpath
            cd testpath/"data" do
              system "#{{bin}}/archivebox", "init"
              system "#{{bin}}/archivebox", "install"
              assert_match "{version}", shell_output("#{{bin}}/archivebox version")
              system "#{{bin}}/archivebox", "status"
            end
          end
        end
        """
    )


def published_wheel(version: str) -> tuple[str, str]:
    with urllib.request.urlopen(
        f"https://pypi.org/pypi/archivebox/{version}/json",
        timeout=20,
    ) as response:
        release = json.load(response)

    wheel_urls = [item for item in release["urls"] if item["filename"].endswith(".whl")]
    if len(wheel_urls) != 1:
        raise RuntimeError(
            f"Expected one published wheel for archivebox=={version}, found {len(wheel_urls)}",
        )
    wheel = wheel_urls[0]
    return wheel["url"], wheel["digests"]["sha256"]


def update_formula() -> int:
    version = os.environ.get("ARCHIVEBOX_VERSION", "")
    if not version:
        raise RuntimeError("ARCHIVEBOX_VERSION is required")
    wheel_url, wheel_sha256 = published_wheel(version)
    new_formula = formula_template(version, wheel_url, wheel_sha256)

    old_formula = FORMULA_PATH.read_text(encoding="utf-8") if FORMULA_PATH.exists() else ""
    changed = old_formula != new_formula

    github_output(
        changed=str(changed).lower(),
        formula_version=version,
    )

    if changed:
        FORMULA_PATH.parent.mkdir(parents=True, exist_ok=True)
        FORMULA_PATH.write_text(new_formula, encoding="utf-8")
        print(f"Updated {FORMULA_PATH.relative_to(REPO_ROOT)} to {version}")
    else:
        print(f"{FORMULA_PATH.relative_to(REPO_ROOT)} already tracks {version}")

    return 0


def main() -> int:
    return update_formula()


if __name__ == "__main__":
    raise SystemExit(main())
